"""Step 8: robustness check: rerun the analysis without the largest 5% of schools (by UGDS).

Large universities have high leverage in the regression (Step 5 diagnostics) and dominate
per-FTE spending denominators. If the coefficients, the ranking, and the spending pattern
survive dropping them, the results are not an artifact of a few big schools.
Also reports: (a) trimmed-sample spending comparison, (b) rank agreement (Spearman) between
full and trimmed residuals, (c) overlap of the top-decile sets.
Outputs: reports/08_robustness.md, results.json["step8"].
"""
import json
from pathlib import Path
import numpy as np
import pandas as pd
import statsmodels.formula.api as smf
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
CLEAN = ROOT / "data" / "clean"
REP = ROOT / "reports"
OUTCOME = "firstgen_comp_orig_yr6_rt"
TRAITS = ["pctpell", "adm_rate", "log_ugds", "pptug_ef", "first_gen", "private", "hbcu_flag", "distance_only"]
CORE = {"exp_instruction": "Instruction", "exp_academic_support": "Academic support", "exp_student_services": "Student services", "exp_institutional_support": "Institutional support", "exp_core": "Core (4 categories)"}


def main() -> None:
    df = pd.read_parquet(CLEAN / "analysis_scored.parquet")
    cut = df["ugds"].quantile(0.95)
    trimmed = df[df["ugds"] <= cut].copy()
    dropped = df[df["ugds"] > cut]
    formula = f"{OUTCOME} ~ " + " + ".join(TRAITS)
    full = smf.ols(formula, data=df).fit(cov_type="HC3")
    trim = smf.ols(formula, data=trimmed).fit(cov_type="HC3")

    coef = pd.DataFrame({"term": full.params.index, "full_coef": full.params.values, "full_p": full.pvalues.values,
                         "trimmed_coef": trim.params.values, "trimmed_p": trim.pvalues.values})
    coef["change"] = coef["trimmed_coef"] - coef["full_coef"]
    coef["change_in_full_SEs"] = coef["change"] / full.bse.values
    same_sign_sig = int(((np.sign(coef.full_coef) == np.sign(coef.trimmed_coef)) & (coef.full_p < 0.05) & (coef.trimmed_p < 0.05)).sum())

    trimmed["residual_trim"] = trim.resid
    trimmed["predicted_trim"] = trim.fittedvalues
    rho = stats.spearmanr(trimmed["residual"], trimmed["residual_trim"]).statistic
    pear = np.corrcoef(trimmed["residual"], trimmed["residual_trim"])[0, 1]
    n_top = int(round(len(trimmed) * 0.10))
    top_full = set(trimmed.nlargest(n_top, "residual")["unitid"])
    top_trim = set(trimmed.nlargest(n_top, "residual_trim")["unitid"])
    overlap = len(top_full & top_trim) / n_top
    # top decile of the full ranking: how many were large schools?
    big_in_top = int((df[df.group == "top 10%"]["ugds"] > cut).sum())
    big_in_bot = int((df[df.group == "bottom 10%"]["ugds"] > cut).sum())

    # spending comparison on trimmed-sample deciles
    trimmed["dec_trim"] = pd.qcut(trimmed["residual_trim"], 10, labels=range(1, 11)).astype(int)
    t, b = trimmed[trimmed.dec_trim == 10], trimmed[trimmed.dec_trim == 1]
    rows = []
    for k, lbl in CORE.items():
        a, c = t[f"{k}_per_fte"], b[f"{k}_per_fte"]
        rows.append({"category": lbl, "top10_median_$": a.median(), "bottom10_median_$": c.median(), "median_ratio": a.median() / c.median(),
                     "welch_p_log": stats.ttest_ind(np.log1p(a), np.log1p(c), equal_var=False).pvalue})
    sp = pd.DataFrame(rows)
    sh = pd.DataFrame([{"category": CORE[k], "top10_mean_share": t[f"{k}_share_core"].mean(), "bottom10_mean_share": b[f"{k}_share_core"].mean(),
                        "diff_pct_pts": (t[f"{k}_share_core"].mean() - b[f"{k}_share_core"].mean()) * 100,
                        "welch_p": stats.ttest_ind(t[f"{k}_share_core"], b[f"{k}_share_core"], equal_var=False).pvalue} for k in list(CORE)[:4]])

    fm = lambda d: d.assign(**{c: d[c].map(lambda v: f"${v:,.0f}") for c in d.columns if c.endswith("_$")}).round(4).to_markdown(index=False)  # noqa: E731
    lines = ["# Robustness check: drop the largest 5% of schools (Step 8)\n", "Generated by `src/08_robustness.py`.\n",
             f"\nCut-off: undergraduate enrollment > {cut:,.0f} (95th percentile). Dropped {len(dropped)} schools (largest: {dropped.nlargest(3,'ugds')['instnm'].tolist()}); {len(trimmed):,} remain.\n",
             f"\n## Coefficients: full sample (n={int(full.nobs):,}, R²={full.rsquared:.3f}) vs trimmed (n={int(trim.nobs):,}, R²={trim.rsquared:.3f})\n", coef.round(4).to_markdown(index=False),
             f"\n\n{same_sign_sig} of {len(coef)} terms keep the same sign and stay significant at 5% in both fits (distance-only was not significant in either). "
             "`change_in_full_SEs` expresses each coefficient shift in units of the full-sample robust standard error; shifts under 1 SE are within noise.\n",
             "\n## Does the ranking change?\n",
             f"- Spearman rank correlation between full-model and trimmed-model residuals (same {len(trimmed):,} schools): {rho:.3f} (Pearson {pear:.3f}).",
             f"- Top-decile overlap: {overlap:.0%} of the {n_top} top-decile schools are the same under both models.",
             f"- In the full ranking, {big_in_top} top-decile and {big_in_bot} bottom-decile schools were among the dropped largest 5%.",
             "\n## Does the spending pattern hold? (trimmed-sample top vs bottom decile)\n", fm(sp), "\n\nShares of core spending:\n", sh.round(4).to_markdown(index=False),
             "\n\nIf instruction and academic support are still higher for over-performers and student-services share is still lower, the Step 7 finding does not depend on the biggest universities.\n"]
    (REP / "08_robustness.md").write_text("\n".join(lines))
    results = json.loads((REP / "results.json").read_text())
    results["step8"] = {"ugds_cut": float(cut), "n_dropped": len(dropped), "n_trimmed": len(trimmed), "r2_full": round(full.rsquared, 4), "r2_trimmed": round(trim.rsquared, 4),
                        "coef_full": {k: round(float(v), 5) for k, v in full.params.items()}, "coef_trimmed": {k: round(float(v), 5) for k, v in trim.params.items()},
                        "max_abs_shift_in_SEs": round(float(coef["change_in_full_SEs"].abs().max()), 3), "same_sign_sig": same_sign_sig,
                        "spearman": round(float(rho), 4), "top_decile_overlap": round(float(overlap), 4), "big_in_top": big_in_top, "big_in_bot": big_in_bot,
                        "spending_trimmed": {r["category"]: {k: round(float(v), 4) for k, v in r.items() if k != "category"} for r in sp.to_dict("records")},
                        "share_trimmed": {r["category"]: {k: round(float(v), 4) for k, v in r.items() if k != "category"} for r in sh.to_dict("records")}}
    (REP / "results.json").write_text(json.dumps(results, indent=2))
    print(coef.round(4).to_string()); print(f"\nrho={rho:.3f} overlap={overlap:.0%} cut={cut:.0f} dropped={len(dropped)}"); print(fm(sp)); print(sh.round(4).to_string())


if __name__ == "__main__":
    main()
